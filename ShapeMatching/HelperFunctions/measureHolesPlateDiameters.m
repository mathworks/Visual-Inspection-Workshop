function measurementResults = measureHolesPlateDiameters(imToMeasure,Rout,holesPlateModel,referenceData,scoreThreshold)
% Measure every detected hole diameter in millimeters.
    if nargin < 5
        scoreThreshold = 0.7;
    end

    matches = matchshape(holesPlateModel,imToMeasure,MaxMatches=5,ScoreThreshold=scoreThreshold);
    measurementResults = table('Size',[0 8],...
        'VariableTypes',{'double','double','double','string','double','double','double','double'},...
        'VariableNames',{'MatchIndex','MatchScore','HoleIndex','HoleType','CenterXInMM','CenterYInMM','RadiusInMM','DiameterInMM'});

    for matchIdx = 1:height(matches)
        tform = convertMatchTransformToWorld(matches(matchIdx).ModelOriginTransformation,Rout);
        circleCenters = transformPointsForward(tform,referenceData.CircleCentersRelativeToModelOrigin);
        circleRadii = transformCircleRadii(tform,...
            referenceData.CircleCentersRelativeToModelOrigin,...
            referenceData.CircleRadiiInMM);

        for holeIdx = 1:size(circleCenters,1)
            measurementData = fitcircle(imToMeasure,...
                [circleCenters(holeIdx,:),circleRadii(holeIdx)],Transformation=Rout,Snap=true);
            if isempty(measurementData.Radius)
                continue
            end

            measurementResults(end+1,:) = { ...
                matchIdx, ...
                matches(matchIdx).Score, ...
                holeIdx, ...
                referenceData.HoleType(holeIdx), ...
                measurementData.Center(1), ...
                measurementData.Center(2), ...
                measurementData.Radius, ...
                2 * measurementData.Radius}; %#ok<AGROW>
        end
    end
end
