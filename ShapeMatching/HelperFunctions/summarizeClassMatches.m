function matchSummary = summarizeClassMatches(matches,partClass)
% Convert a match array into a compact class/score summary table.
    matchSummary = table('Size',[0 3],...
        'VariableTypes',{'string','string','double'},...
        'VariableNames',{'PartClass','ClassName','Score'});

    for matchIdx = 1:height(matches)
        matchSummary(end+1,:) = { ...
            string(partClass), ...
            string(matches(matchIdx).ClassName), ...
            matches(matchIdx).Score}; %#ok<AGROW>
    end
end
